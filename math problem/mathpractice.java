public class mathpractice {
    public static void main(String[] args) {
        System.out.println(Math.sqrt(5));
        System.out.println(Math.max(5, 10));
        System.out.println(Math.min(5, 10));
        System.out.println(Math.abs(-4.89));
        System.out.println(Math.pow(2, 8)); //2 multiple by 8 times 2 * 2 * 2 * 2 * 2 * 2 * 2 * 2 = 256
        System.out.println(Math.round(4.6));
        System.out.println(Math.ceil(4.1));  //rounds up (returns the smallest integer greater than or equal to x)
        System.out.println(Math.floor(4.9));//rounds down (returns the largest integer less than or equal to x)

        System.out.println(Math.random());
        
    }
}
